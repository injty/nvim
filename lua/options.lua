-- Синхронизация с системным буфером обмена
-- Позволяет копировать и вставлять текст между Neovim и другими программами (через cmd+c / cmd+v) без лишних биндов
vim.o.clipboard = "unnamedplus"

-- Глобальная строка состояния (statusline)
-- Значение 3 включает одну общую строку статуса для всех окон, вместо отдельных для каждого сплита
vim.o.laststatus = 3

-- Подсветка результатов поиска
-- Отключена, чтобы совпадения не оставались постоянно желтыми после поиска через /
vim.o.hlsearch = false

-- Включение нумерации строк по умолчанию
vim.wo.number = true

-- Включение поддержки мыши
-- Режим "a" позволяет кликать, выделять текст и скроллить колесиком внутри Neovim
vim.o.mouse = "a"

-- Умный перенос строк с сохранением отступов
-- Перенесенный кусок длинной строки будет начинаться с тем же отступом, что и начало строки
vim.o.breakindent = true

-- Сохранение истории отмен (Undo) между перезапусками редактора
-- Даже если ты закроешь файл, выключишь Mac, а завтра вернешься — ты сможешь отменить изменения через 'u'
vim.o.undofile = true

-- Отключение создания swap-файлов (.swp)
vim.o.swapfile = false

-- Вертикальный и горизонтальный отступы при скролле
-- Экран начнет автоматически скроллиться, когда курсор окажется в 5 строках (или символах) от края
vim.o.scrolloff = 15
vim.o.sidescrolloff = 15

-- Поиск без учета регистра букв, ЕСЛИ в запросе нет заглавных букв
-- Поиск /react найдет и "React", и "react". Но поиск /React найдет строго слово с большой буквы.
vim.o.ignorecase = true
vim.o.smartcase = true

-- Уменьшение времени обновления интервала (в миллисекундах)
-- Быстрее триггерит автокоманды и выводит диагностику/ошибки от LSP на экран
vim.o.updatetime = 250

-- Всегда показывать боковую колонку знаков (Sign Column)
-- Предотвращает раздражающее "дергание" кода влево-вправо, когда на полях появляются иконки ошибок или гита
vim.wo.signcolumn = "yes"

-- Включение поддержки True Color (24-битный цвет)
-- Необходимо, чтобы современные темы оформления отображались сочными и правильными оттенками
vim.o.termguicolors = true

-- Настройка поведения встроенного меню автодополнения
-- menuone — открывать меню, даже если совпадение всего одно; noselect — не выбирать первый пункт автоматически
vim.o.completeopt = "menuone,noselect"

-- Логичное поведение при разделении экрана (сплитах)
-- Новые окна будут открываться строго справа и снизу от текущего
vim.opt.splitright = true
vim.opt.splitbelow = true

-- Отключение отображения текущего режима (например, -- INSERT --) в самом низу
-- Нам это больше не нужно, так как режим обычно красиво показывает твоя статус-строка (lualine)
vim.o.showmode = false

-- Установка клавиши <Space> (Пробел) в качестве главного Leader-ключа
-- ВАЖНО: Эти строчки должны идти до загрузки плагинов, иначе у них привяжется старый дефолтный Leader (обратный слэш)
vim.g.mapleader = " "
vim.g.maplocalleader = " "

-- Настройки отступов и табуляции
vim.opt.tabstop = 2 -- Ширина знака табуляции в пробелах
vim.opt.shiftwidth = 2 -- Размер отступа при форматировании (команды << и >>)
vim.opt.softtabstop = 2 -- Сколько пробелов вставляется, если нажать Tab в режиме вставки
